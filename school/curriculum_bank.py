def entry(grade,subject,q,correct,wrong,explanation,sequence):
    options=[str(correct)]+[str(x) for x in wrong]
    if len(options)!=4 or len(set(options))!=4:raise ValueError("Duplicate choices")
    rng=random.Random(grade*10000+sequence*31+sum(ord(c) for c in subject))
    rng.shuffle(options)
    return {"grade":grade,"subject":subject,"topic":SUBJECTS[subject],"q":q,"choices":options,"answer":options.index(str(correct)),"explanation":explanation}
def math_questions(grade):
    result=[]
    for i in range(1,21):
        if grade==1:
            a,b=2+i%8,1+(i*2)%7
            if i%3==0:
                q,ans=f"{a+b} - {b} = කීයද?",a
            else:q,ans=f"{a} + {b} = කීයද?",a+b
            expl=f"පියවරෙන් ගණනය කළ විට පිළිතුර {ans}යි."
        elif grade==2:
            a,b=15+i*3,2+i%10
            if i%2:q,ans=f"{a} - {b} = කීයද?",a-b
            else:q,ans=f"{a} + {b} = කීයද?",a+b
            expl=f"එකතු කිරීම හෝ අඩු කිරීමෙන් {ans} ලැබේ."
