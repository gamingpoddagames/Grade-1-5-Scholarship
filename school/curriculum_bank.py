def get_questions():
    bank=[]
    for grade in range(1,6):
        bank.extend(math_questions(grade))
        for subject,dataset in (("sinhala",LANGUAGE),("environment",ENVIRONMENT)):
            for idx,row in enumerate(dataset[grade],1):
                q,correct,w1,w2,w3,explanation=row
                bank.append(entry(grade,subject,q,correct,[w1,w2,w3],explanation,100+idx))
    return bank
